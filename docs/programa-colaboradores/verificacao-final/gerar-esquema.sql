-- Gera o DDL (SOMENTE o esquema, sem dados) do schema `public` de um banco, por consultas de CATÁLOGO. Somente leitura.
-- Uso (no banco de ORIGEM; ex.: o do Backfindr, em modo leitura):
--   SET search_path = public;   -- faz as funções pg_get_* devolverem nomes SEM o prefixo «public.»
--   psql "<origem>" -At -c "SET search_path = public" -f gerar-esquema.sql > esquema.sql      (uma única coluna `esquema` com o script inteiro)
-- Aplicação no banco de DESTINO: `CREATE SCHEMA backfindr_teste; SET search_path = backfindr_teste, extensions;` e depois o conteúdo gerado.
-- As funções, índices e gatilhos saem com o prefixo `public.` removido (o destino usa o próprio schema no search_path).
-- NÃO gera: extensões (instalar à parte), papéis, permissões (GRANT), comentários e DADOS.
WITH
ext_owned AS (SELECT objid FROM pg_depend WHERE deptype = 'e'),
nsp AS (SELECT oid FROM pg_namespace WHERE nspname = 'public'),
enums AS (
  SELECT 10 AS etapa, t.typname AS ordem,
         format('CREATE TYPE %I AS ENUM (%s)', t.typname, (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid)) AS ddl
    FROM pg_type t WHERE t.typnamespace = (SELECT oid FROM nsp) AND t.typtype = 'e' AND t.oid NOT IN (SELECT objid FROM ext_owned)
),
seqs AS (
  SELECT 20, c.relname, format('CREATE SEQUENCE %I', c.relname)
    FROM pg_class c LEFT JOIN pg_depend d ON d.objid = c.oid AND d.deptype = 'i'
   WHERE c.relnamespace = (SELECT oid FROM nsp) AND c.relkind = 'S' AND d.objid IS NULL      -- identidade cria a própria sequência
),
tabelas AS (
  SELECT 30, c.relname,
         format('CREATE TABLE %I (%s)', c.relname,
           (SELECT string_agg(
               format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                      CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
                      CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                           WHEN ad.adbin IS NOT NULL AND a.attidentity = '' THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END,
                      CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END), ', ' ORDER BY a.attnum)
              FROM pg_attribute a LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
             WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped))
    FROM pg_class c WHERE c.relnamespace = (SELECT oid FROM nsp) AND c.relkind IN ('r','p') AND c.oid NOT IN (SELECT objid FROM ext_owned)
),
dono_seq AS (
  SELECT 35, s.relname || '.' || a.attname,
         format('ALTER SEQUENCE %I OWNED BY %I.%I', s.relname, t.relname, a.attname)
    FROM pg_depend d JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S' JOIN pg_class t ON t.oid = d.refobjid
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
   WHERE d.deptype = 'a' AND s.relnamespace = (SELECT oid FROM nsp)
),
restricoes AS (   -- chave primária, únicas, checks e exclusões
  SELECT 40, c.relname || '.' || k.conname,
         format('ALTER TABLE %I ADD CONSTRAINT %I %s', c.relname, k.conname, pg_get_constraintdef(k.oid))
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid
   WHERE c.relnamespace = (SELECT oid FROM nsp) AND k.contype IN ('p','u','c','x') AND c.relkind IN ('r','p')
),
indices AS (      -- índices que não sustentam restrição
  SELECT 50, i.indexrelid::regclass::text, replace(pg_get_indexdef(i.indexrelid), ' ON public.', ' ON ')
    FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid
   WHERE c.relnamespace = (SELECT oid FROM nsp) AND c.relkind IN ('r','p')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid)
),
chaves_estrangeiras AS (
  SELECT 60, c.relname || '.' || k.conname,
         format('ALTER TABLE %I ADD CONSTRAINT %I %s', c.relname, k.conname, pg_get_constraintdef(k.oid))
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid
   WHERE c.relnamespace = (SELECT oid FROM nsp) AND k.contype = 'f' AND c.relkind IN ('r','p')
),
funcoes AS (
  SELECT 70, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', regexp_replace(pg_get_functiondef(p.oid), '^CREATE OR REPLACE (FUNCTION|PROCEDURE) public\.', 'CREATE OR REPLACE \1 ')
    FROM pg_proc p WHERE p.pronamespace = (SELECT oid FROM nsp) AND p.prokind IN ('f','p') AND p.oid NOT IN (SELECT objid FROM ext_owned)
),
visoes AS (
  SELECT 80, c.relname, format('CREATE %s %I AS %s', CASE c.relkind WHEN 'm' THEN 'MATERIALIZED VIEW' ELSE 'VIEW' END, c.relname, rtrim(pg_get_viewdef(c.oid), ';'))
    FROM pg_class c WHERE c.relnamespace = (SELECT oid FROM nsp) AND c.relkind IN ('v','m') AND c.oid NOT IN (SELECT objid FROM ext_owned)
),
gatilhos AS (
  SELECT 90, c.relname || '.' || t.tgname, replace(replace(pg_get_triggerdef(t.oid), ' ON public.', ' ON '), 'EXECUTE FUNCTION public.', 'EXECUTE FUNCTION ')
    FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid WHERE c.relnamespace = (SELECT oid FROM nsp) AND NOT t.tgisinternal
),
rls AS (
  SELECT 95, c.relname, format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', c.relname)
    FROM pg_class c WHERE c.relnamespace = (SELECT oid FROM nsp) AND c.relkind IN ('r','p') AND c.relrowsecurity
),
politicas AS (
  SELECT 96, p.tablename || '.' || p.policyname,
         format('CREATE POLICY %I ON %I AS %s FOR %s TO %s%s%s', p.policyname, p.tablename, p.permissive, p.cmd,
                array_to_string(p.roles, ', '), COALESCE(' USING (' || p.qual || ')', ''), COALESCE(' WITH CHECK (' || p.with_check || ')', ''))
    FROM pg_policies p WHERE p.schemaname = 'public'
)
SELECT string_agg(ddl || ';', E'\n\n' ORDER BY etapa, ordem) AS esquema FROM (
  SELECT * FROM enums UNION ALL SELECT * FROM seqs UNION ALL SELECT * FROM tabelas UNION ALL SELECT * FROM dono_seq UNION ALL SELECT * FROM restricoes
  UNION ALL SELECT * FROM indices UNION ALL SELECT * FROM chaves_estrangeiras UNION ALL SELECT * FROM funcoes UNION ALL SELECT * FROM visoes
  UNION ALL SELECT * FROM gatilhos UNION ALL SELECT * FROM rls UNION ALL SELECT * FROM politicas
) x(etapa, ordem, ddl);
